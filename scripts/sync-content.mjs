#!/usr/bin/env node
/**
 * 生成站点里那几个「算出来」的页面：
 *
 *   docs/index.md                    书架首页（列出全部作品）
 *   docs/novels/<作品>/index.md       作品首页（简介、章数、字数、目录）
 *   docs/public/novels/<slug>/cover.jpg  封面（压到 900px 宽）
 *
 * 正文（章节、许可页）现在就直接放在 docs/novels/<作品>/ 里，不再复制。
 * 「作品文件夹 → 网址」的映射见 scripts/lib/novels.mjs 与 .vitepress/config.mts。
 *
 * 生成的文件末尾有一行 generated 标记；想自己写这两个页面，把标记删掉即可，脚本就不覆盖了。
 * 手动同步：npm run docs:sync
 */
import fs from 'node:fs'
import path from 'node:path'
import { execFileSync } from 'node:child_process'
import { fileURLToPath } from 'node:url'
import { escapeHtml, loadNovels, readText, yaml } from './lib/novels.mjs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const docsDir = path.join(root, 'docs')
const contentDir = path.join(docsDir, 'novels')
const siteFile = path.join(docsDir, 'site.json')
const publicNovelsDir = path.join(docsDir, 'public/novels')

const MARK = '<!-- generated by scripts/sync-content.mjs -->'
const log = (...args) => console.log('[sync]', ...args)

if (!fs.existsSync(contentDir)) {
  console.error(`[sync] 找不到作品目录：${contentDir}`)
  process.exit(1)
}

const { site, novels } = loadNovels(contentDir, { siteFile })

if (novels.length === 0) {
  console.error(`[sync] ${contentDir} 里还没有作品文件夹。结构应为 docs/novels/<作品名>/01-第一章.md`)
  process.exit(1)
}

/** 写入生成物；如果文件被改成手写版（没有 generated 标记）就不覆盖 */
function writeGenerated(file, content) {
  const existing = readText(file)
  if (existing && !existing.includes(MARK)) {
    log(`保留手写的 ${path.relative(root, file)}（没有 generated 标记，不覆盖）`)
    return
  }
  fs.writeFileSync(file, `${content}\n${MARK}\n`)
}

fs.mkdirSync(publicNovelsDir, { recursive: true })

for (const novel of novels) {
  writeGenerated(path.join(novel.sourceDir, 'index.md'), landingPage(novel, site))

  if (novel.cover) {
    const coverDir = path.join(publicNovelsDir, novel.slug)
    fs.mkdirSync(coverDir, { recursive: true })
    compressCover(path.join(novel.sourceDir, novel.coverFile), path.join(coverDir, 'cover.jpg'))
  }

  log(
    `《${novel.title}》：${novel.chapters.length} 篇、${novel.stats.chapters} 章、` +
      `约 ${(novel.stats.words / 10000).toFixed(1)} 万字 → ${novel.home}`
  )
}

writeGenerated(path.join(docsDir, 'index.md'), homePage(novels, site))

// 旧版结构留下的产物
for (const legacy of [
  path.join(docsDir, 'chapters'),
  path.join(docsDir, 'license.md'),
  path.join(docsDir, 'public/cover.jpg')
]) {
  fs.rmSync(legacy, { recursive: true, force: true })
}

log(`书架：${novels.length} 部作品`)

/* ============================================================
   页面内容
   ============================================================ */

/** 作品首页 */
function landingPage(novel, site) {
  const { stats } = novel
  const lines = ['---', `title: ${yaml(novel.title)}`, 'pageClass: novel-home', '---', '']
  lines.push(`# ${novel.title}`, '')
  if (novel.tagline) lines.push(`> ${novel.tagline}`, '')
  if (novel.description) lines.push(novel.description, '')

  const metaParts = []
  if (novel.author && novel.author !== site.author) metaParts.push(`作者：${novel.author}`)
  if (novel.status) metaParts.push(`**${novel.status}**`)
  if (stats.chapters) metaParts.push(`${stats.chapters} 章`)
  if (stats.chapters === 0 && stats.extras.length) metaParts.push(`${stats.extras.length} 篇`)
  metaParts.push(`约 ${(stats.words / 10000).toFixed(1)} 万字`)
  lines.push(`${metaParts.join(' · ')}。`, '')

  const first = novel.chapters[0]
  lines.push('<p class="novel-actions">')
  lines.push(`  <a class="novel-btn primary" href="${first.href}">开始阅读</a>`)
  if (novel.licensePage) {
    lines.push(`  <a class="novel-btn" href="${novel.licensePage}">作品许可</a>`)
  }
  lines.push('</p>', '')

  lines.push('## 目录', '')
  novel.chapters.forEach((chapter, index) => {
    lines.push(`${index + 1}. [${chapter.listText}](${chapter.href})`)
  })
  lines.push('')

  return lines.join('\n')
}

/** 书架首页 */
function homePage(novels, site) {
  const lines = ['---', 'layout: home', '', 'hero:', `  name: ${yaml(site.title)}`]
  if (site.tagline) lines.push(`  tagline: ${yaml(site.tagline)}`)
  lines.push('---', '')

  // 按 site.json 里的 sections 分组，每组一段标题 + 卡片
  const groups = site.sections
    .map((section) => ({
      title: section.title,
      description: section.description || '',
      items: novels.filter((novel) => novel.category === section.id)
    }))
    .filter((group) => group.items.length > 0)

  // novel.json 里写了没声明过的 category，兜个底，别让它从书架上消失
  const declared = new Set(site.sections.map((section) => section.id))
  const others = novels.filter((novel) => !declared.has(novel.category))
  if (others.length > 0) {
    groups.push({ title: '其他', description: '', items: others })
  }

  for (const group of groups) {
    lines.push(`## ${group.title}`, '')
    if (group.description) lines.push(group.description, '')
    // 卡片是原生 HTML：一行一个，中间不留空行，markdown 会整段原样输出
    lines.push('<div class="shelf-grid">')
    for (const novel of group.items) {
      const description = novel.tagline || novel.description
      lines.push(`  <a class="shelf-card" href="${novel.home}">`)
      lines.push(`    <span class="shelf-title">${escapeHtml(novel.title)}</span>`)
      lines.push(`    <span class="shelf-meta">${escapeHtml(cardMeta(novel, site))}</span>`)
      if (description) {
        lines.push(`    <span class="shelf-desc">${escapeHtml(description)}</span>`)
      }
      lines.push('    <span class="shelf-more">开始阅读 →</span>')
      lines.push('  </a>')
    }
    lines.push('</div>', '')
  }

  return lines.join('\n')
}

/** 卡片上那行小字：作者（非本人作品）· 状态 · 章数/篇数 · 字数 */
function cardMeta(novel, site) {
  const parts = []
  if (novel.author && novel.author !== site.author) parts.push(`${novel.author} 著`)
  if (novel.status) parts.push(novel.status)
  if (novel.stats.chapters) {
    parts.push(`${novel.stats.chapters} 章`)
  } else if (novel.stats.extras.length) {
    parts.push(`${novel.stats.extras.length} 篇`)
  }
  parts.push(`约 ${(novel.stats.words / 10000).toFixed(1)} 万字`)
  return parts.join(' · ')
}

/** 用 ImageMagick 把封面缩到 900px 宽、转成 jpg */
function compressCover(source, target) {
  const args = [source, '-resize', '900x>', '-strip', '-quality', '88', target]
  for (const bin of ['magick', 'convert']) {
    try {
      execFileSync(bin, args, { stdio: 'ignore' })
      return true
    } catch {
      // 换下一个命令再试
    }
  }
  log('提示：没找到 ImageMagick（magick / convert），封面跳过压缩')
  return false
}
